--
-- ## 1. List All Plug Mappings
--
-- Use the `:map` command with a filter to see all `<Plug>` mappings:
--
-- ```vim
-- :map <Plug>
-- :nmap <Plug>
-- :vmap <Plug>
-- :imap <Plug>
-- ```
--
-- This will show all mappings that contain `<Plug>` in their left-hand side.
--
-- ## 2. Search for Specific Plug Mappings
--
-- To find a specific `<Plug>` mapping:
--
-- ```vim
-- :map <Plug>PluginName
-- :nmap <Plug>CommentToggle
-- ```
--
-- ## 3. Use Verbose Mapping to See Source
--
-- The `:verbose` command shows where a mapping was defined:
--
-- ```vim
-- :verbose map <Plug>CommentToggle
-- :verbose nmap <Plug>SomeMapping
-- ```
--
-- This will show the file and line number where the mapping was created.
--
-- ## 4. Use maparg() Function
--
-- The `maparg()` function returns mapping details:
--
-- ```vim
-- :echo maparg('<Plug>CommentToggle', 'n')
-- :echo maparg('<Plug>SomeMapping', 'v', 0, 1)
-- ```
--
-- The last parameter (1) returns a dictionary with detailed information including where it was defined.
--
-- ## 5. Use maplist() Function (Neovim 0.8+)
