local fixer = require("glyph-guard.fixer")

describe("glyph_guard.fixer.parse_comment", function()
  it("returns the whole line as code when prefix is absent", function()
    local code, base, section = fixer.parse_comment("local x = 1", "--")
    assert.are.equal("local x = 1", code)
    assert.is_nil(base)
    assert.is_nil(section)
  end)

  it("extracts base comment when no glyph section present", function()
    local code, base, section = fixer.parse_comment("local x = 1 -- hello", "--")
    assert.are.equal("local x = 1 ", code)
    assert.are.equal("hello", base)
    assert.is_nil(section)
  end)

  it("splits base comment and glyph section", function()
    local code, base, section = fixer.parse_comment('local x = "" -- foo | U+E0B0 \u{E0B0}', "--")
    assert.are.equal('local x = "" ', code)
    assert.are.equal("foo", base)
    assert.are.equal("U+E0B0 \u{E0B0}", section)
  end)

  it("returns nil base when only a glyph section exists", function()
    local code, base, section = fixer.parse_comment('local x = "" -- U+E0B0 \u{E0B0}', "--")
    assert.are.equal('local x = "" ', code)
    assert.is_nil(base)
    assert.are.equal("U+E0B0 \u{E0B0}", section)
  end)

  it("does not consume user U+HEX text without following glyph token", function()
    local code, base, section = fixer.parse_comment("local x = 1 -- see U+00A0", "--")
    assert.are.equal("local x = 1 ", code)
    assert.are.equal("see U+00A0", base)
    assert.is_nil(section)
  end)
end)
